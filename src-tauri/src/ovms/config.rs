//! Generates the on-disk config files OVMS needs to serve a single model
//! over its OpenAI-compatible REST endpoints.
//!
//! Layout:
//!
//! ```text
//! state/
//!   config.json                  ← passed to `ovms.exe --config_path`
//! models/<org>/<repo>/
//!   graph.pbtxt                  ← MediaPipe graph (lives next to weights)
//!   .zero_model.json             ← per-model deploy params (task + knobs)
//!   openvino_model.xml / .bin
//!   tokenizer / detokenizer …
//! ```
//!
//! The graph lives inside the model directory (using `model_path: "./"`)
//! so the layout matches the canonical one produced by `export_model.py`
//! in `openvinotoolkit/model_server`. It is rewritten on every `prepare`
//! so settings + task-param changes take effect on the next start.
//!
//! To stay polite to curated bundles that ship their own `graph.pbtxt`,
//! we tag every graph we author with [`ZERO_MARKER`] and only overwrite
//! files that carry the marker.

use crate::hf::{
    params::{self, ModelDeployParams},
    EmbeddingsParams, ImageGenParams, ModelTask, RerankParams, S2tParams, T2sParams, TextGenParams,
};
use crate::paths;
use anyhow::{Context, Result};
use serde::Serialize;
use serde_json::json;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Sentinel embedded as a leading comment in any `graph.pbtxt` we author.
/// Used by [`safe_to_overwrite`] so subsequent runs can refresh our own
/// graph without ever clobbering a user- or model-author-supplied one.
pub const ZERO_MARKER: &str = "# Generated by zero";

/// Inputs the controller assembles per model before each `start` /
/// reload. The controller passes a slice of these to [`prepare`] so a
/// single `config.json` can declare every model the user wants OVMS to
/// keep loaded simultaneously (text-gen + embeddings + rerank + s2t +
/// t2s + image-gen all in one process).
#[derive(Debug, Clone)]
pub struct PrepareInput<'a> {
    /// Logical name the model is served under. Becomes the `model` field in
    /// chat completion requests, so callers should use a value that's stable
    /// for the lifetime of the conversation (we pass the HF id).
    pub model_name: &'a str,
    /// Directory on disk holding the OpenVINO IR + tokenizer files. The
    /// `graph.pbtxt` we own is written into this directory.
    pub model_dir: &'a Path,
    /// Inference device hint: `CPU`, `GPU`, `NPU`, `AUTO`, ...
    pub device: &'a str,
}

/// Paths the controller hands to `ovms.exe`.
#[derive(Debug, Clone, Serialize)]
pub struct ServerConfig {
    pub config_path: PathBuf,
    /// Per-model `graph.pbtxt` paths in the same order as the inputs.
    pub graph_paths: Vec<PathBuf>,
    /// Per-model logical names in the same order as the inputs.
    pub model_names: Vec<String>,
}

/// Materialise the config + graph files for `inputs`. Idempotent;
/// re-running with the same inputs is safe and cheap.
///
/// Every model gets its own `<model_dir>/graph.pbtxt` (re-rendered so the
/// latest device + task params land on disk, unless an external graph is
/// already in place), and the resulting paths are stitched into a single
/// `config.json` with one `mediapipe_config_list` entry per model. OVMS
/// then exposes the OpenAI-compat endpoint for each of them in parallel
/// — the `model` field in the request routes to the right graph.
///
/// Passing an empty `inputs` slice writes a config with empty model and
/// mediapipe lists. OVMS is happy to come up that way; the controller
/// uses it as a starting point before staging the first model.
pub fn prepare(inputs: &[PrepareInput<'_>]) -> Result<ServerConfig> {
    let state = paths::ovms_state_dir()?;
    prepare_into(inputs, &state)
}

/// Same as [`prepare`], but writes `config.json` under `state_dir`
/// instead of the canonical runtime dir. Used by unit tests so they can
/// route the side-effect into a scratch directory without racing on the
/// shared OVMS config under `~/.zero/runtimes/ovms/`.
pub fn prepare_into(inputs: &[PrepareInput<'_>], state_dir: &Path) -> Result<ServerConfig> {
    let mut mediapipe_entries: Vec<serde_json::Value> = Vec::with_capacity(inputs.len());
    let mut graph_paths: Vec<PathBuf> = Vec::with_capacity(inputs.len());
    let mut model_names: Vec<String> = Vec::with_capacity(inputs.len());

    for input in inputs {
        let params = params::read_or_default(input.model_dir);
        let graph_path = ensure_in_model_graph(input.model_dir, input.device, &params)
            .with_context(|| format!("write graph.pbtxt for {}", input.model_dir.display()))?;

        mediapipe_entries.push(json!({
            "name": input.model_name,
            // `base_path` is what OVMS uses as the workspace for relative
            // paths inside the graph (e.g. `models_path: "./"`). Without
            // it, OVMS derives `<workspace>/<name>` — and our `name` is
            // the HF id (`org/repo`), which would push the lookup into a
            // non-existent subdirectory of the OVMS runtime root. Pin it
            // to the model dir so the relative `models_path` in
            // graph.pbtxt resolves correctly.
            "base_path": input.model_dir.to_string_lossy(),
            "graph_path": graph_path.to_string_lossy(),
        }));
        graph_paths.push(graph_path);
        model_names.push(input.model_name.to_string());
    }

    std::fs::create_dir_all(state_dir).with_context(|| format!("create {state_dir:?}"))?;
    let config_path = state_dir.join("config.json");
    let config_body = json!({
        "model_config_list": [],
        "mediapipe_config_list": mediapipe_entries,
    });
    std::fs::write(&config_path, serde_json::to_vec_pretty(&config_body)?)
        .with_context(|| format!("write {config_path:?}"))?;

    Ok(ServerConfig {
        config_path,
        graph_paths,
        model_names,
    })
}

/// Write (or refresh) `<model_dir>/graph.pbtxt` for `device` + `params`.
///
/// Called both from [`prepare`] at server-start time and from the HF
/// download pipeline at install time so a freshly downloaded model is
/// immediately serveable by OVMS without any extra setup step.
///
/// If an existing `graph.pbtxt` is present and does **not** carry
/// [`ZERO_MARKER`], we treat it as user/curator-owned and leave it intact.
pub fn ensure_in_model_graph(
    model_dir: &Path,
    device: &str,
    params: &ModelDeployParams,
) -> Result<PathBuf> {
    std::fs::create_dir_all(model_dir).with_context(|| format!("create {model_dir:?}"))?;
    let path = model_dir.join("graph.pbtxt");

    if !safe_to_overwrite(&path) {
        tracing::debug!(
            "graph.pbtxt at {} is externally managed (no zero marker) — leaving as-is",
            path.display()
        );
        return Ok(path);
    }

    // Per-model `device` override wins over the runtime setting passed in;
    // when absent we fall back to the global OVMS device the caller resolved.
    let effective_device = params
        .device
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .unwrap_or(device);
    let body = render_graph(effective_device, &params.task);
    std::fs::write(&path, body).with_context(|| format!("write {path:?}"))?;
    Ok(path)
}

/// Returns `true` when the file is missing or was authored by zero
/// (carries [`ZERO_MARKER`] in its first chunk). Anything else is assumed
/// to be a hand-written or upstream-curated graph that we shouldn't touch.
fn safe_to_overwrite(path: &Path) -> bool {
    use std::io::Read;
    let Ok(mut f) = std::fs::File::open(path) else {
        return true; // missing → ours to write
    };
    let mut buf = [0u8; 512];
    let n = match f.read(&mut buf) {
        Ok(n) => n,
        Err(_) => return false, // unreadable → be conservative
    };
    std::str::from_utf8(&buf[..n])
        .map(|s| s.contains(ZERO_MARKER))
        .unwrap_or(false)
}

/// Common header for every zero-authored graph.
fn header() -> String {
    format!(
        "{marker} — refreshed on each start from .zero_model.json + ovms settings.\n# Delete this marker line to take ownership and stop zero from regenerating.\n# OVMS_GRAPH_QUEUE_MAX_SIZE: AUTO\n",
        marker = ZERO_MARKER
    )
}

/// Dispatch to the per-task template. Mirrors the six families exposed by
/// upstream `export_model.py`.
fn render_graph(device: &str, task: &ModelTask) -> String {
    match task {
        ModelTask::TextGeneration(p) => render_text_generation(device, p),
        ModelTask::Embeddings(p) => render_embeddings(device, p),
        ModelTask::Rerank(p) => render_rerank(device, p),
        ModelTask::ImageGeneration(p) => render_image_generation(device, p),
        ModelTask::Text2Speech(p) => render_text2speech(device, p),
        ModelTask::Speech2Text(p) => render_speech2text(device, p),
    }
}

// ─── Text generation ───────────────────────────────────────────────────────

fn render_text_generation(device: &str, p: &TextGenParams) -> String {
    // Build the inner `LLMCalculatorOptions` body so we can include only
    // the optional fields the user actually set — matches what the jinja
    // template does in `export_model.py`.
    let mut body = String::new();
    let mut push = |s: &str| body.push_str(s);

    if let Some(t) = &p.pipeline_type {
        push(&format!("          pipeline_type: {t},\n"));
    }
    push("          models_path: \"./\",\n");
    let plugin_config = build_text_gen_plugin_config(device, p);
    push(&format!("          plugin_config: '{plugin_config}',\n"));
    push(&format!(
        "          enable_prefix_caching: {},\n",
        bool_str(p.enable_prefix_caching)
    ));
    push(&format!("          cache_size: {},\n", p.cache_size));
    if let Some(v) = p.max_num_batched_tokens {
        push(&format!("          max_num_batched_tokens: {v},\n"));
    }
    if !p.dynamic_split_fuse {
        push("          dynamic_split_fuse: false,\n");
    }
    push(&format!("          max_num_seqs: {},\n", p.max_num_seqs));
    push(&format!("          device: \"{device}\",\n"));
    if let Some(r) = &p.reasoning_parser {
        push(&format!("          reasoning_parser: \"{r}\",\n"));
    }
    if let Some(t) = &p.tool_parser {
        push(&format!("          tool_parser: \"{t}\",\n"));
    }
    if p.enable_tool_guided_generation {
        push("          enable_tool_guided_generation: true,\n");
    }

    format!(
        r#"{header}input_stream: "HTTP_REQUEST_PAYLOAD:input"
output_stream: "HTTP_RESPONSE_PAYLOAD:output"

node: {{
  name: "LLMExecutor"
  calculator: "HttpLLMCalculator"
  input_stream: "LOOPBACK:loopback"
  input_stream: "HTTP_REQUEST_PAYLOAD:input"
  input_side_packet: "LLM_NODE_RESOURCES:llm"
  output_stream: "LOOPBACK:loopback"
  output_stream: "HTTP_RESPONSE_PAYLOAD:output"
  input_stream_info: {{
    tag_index: 'LOOPBACK:0',
    back_edge: true
  }}
  node_options: {{
      [type.googleapis.com / mediapipe.LLMCalculatorOptions]: {{
{body}      }}
  }}
  input_stream_handler {{
    input_stream_handler: "SyncSetInputStreamHandler",
    options {{
      [mediapipe.SyncSetInputStreamHandlerOptions.ext] {{
        sync_set {{
          tag_index: "LOOPBACK:0"
        }}
      }}
    }}
  }}
}}
"#,
        header = header(),
    )
}

/// Construct the inner JSON `plugin_config` value consumed by the
/// LLMCalculator. Matches the construction logic in `export_model.py`:
///
/// - `KV_CACHE_PRECISION` is forwarded as-is.
/// - `prompt_lookup` is forwarded when enabled.
/// - For HETERO devices, model distribution policy is pinned.
/// - For NPU, prefix-caching + max-prompt-len flow through `DEVICE_PROPERTIES`.
fn build_text_gen_plugin_config(device: &str, p: &TextGenParams) -> String {
    let mut map = serde_json::Map::new();
    if let Some(v) = &p.kv_cache_precision {
        map.insert("KV_CACHE_PRECISION".into(), serde_json::json!(v));
    }
    if p.prompt_lookup_decoding {
        map.insert("prompt_lookup".into(), serde_json::json!(true));
    }
    if device.contains("HETERO") {
        map.insert(
            "MODEL_DISTRIBUTION_POLICY".into(),
            serde_json::json!("PIPELINE_PARALLEL"),
        );
    }
    if device == "NPU" {
        let mut npu = serde_json::Map::new();
        if let Some(v) = p.max_prompt_len {
            npu.insert("MAX_PROMPT_LEN".into(), serde_json::json!(v));
        }
        if p.enable_prefix_caching {
            npu.insert(
                "NPUW_LLM_ENABLE_PREFIX_CACHING".into(),
                serde_json::json!(true),
            );
        }
        if !npu.is_empty() {
            let mut device_props = serde_json::Map::new();
            device_props.insert("NPU".into(), serde_json::Value::Object(npu));
            map.insert(
                "DEVICE_PROPERTIES".into(),
                serde_json::Value::Object(device_props),
            );
        }
    }
    // protobuf textproto demands a single-quoted JSON string; bare `'`
    // inside would break it. Our values never include one, but use a
    // strict serialiser anyway.
    serde_json::to_string(&serde_json::Value::Object(map)).unwrap_or_else(|_| "{}".into())
}

// ─── Embeddings ────────────────────────────────────────────────────────────

fn render_embeddings(device: &str, p: &EmbeddingsParams) -> String {
    let truncate_line = if p.truncate {
        "          truncate: true,\n"
    } else {
        ""
    };
    format!(
        r#"{header}input_stream: "REQUEST_PAYLOAD:input"
output_stream: "RESPONSE_PAYLOAD:output"
node {{
  name: "EmbeddingsExecutor"
  input_side_packet: "EMBEDDINGS_NODE_RESOURCES:embeddings_servable"
  calculator: "EmbeddingsCalculatorOV"
  input_stream: "REQUEST_PAYLOAD:input"
  output_stream: "RESPONSE_PAYLOAD:output"
  node_options: {{
      [type.googleapis.com / mediapipe.EmbeddingsCalculatorOVOptions]: {{
          models_path: "./",
          plugin_config: '{{"NUM_STREAMS": "{streams}" }}',
          normalize_embeddings: {normalize},
          pooling: {pooling},
{truncate}          target_device: "{device}"
      }}
  }}
}}
"#,
        header = header(),
        streams = p.num_streams,
        normalize = bool_str(p.normalize),
        pooling = p.pooling,
        truncate = truncate_line,
    )
}

// ─── Rerank ────────────────────────────────────────────────────────────────

